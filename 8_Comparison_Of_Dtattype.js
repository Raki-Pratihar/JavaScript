// 8️⃣ Coparision Of Datatype

// 1. > , < , >= , <= 
console.log(2 > 1);
console.log(2 < 1);
console.log(2 >= 2);
console.log(2 <= 10);

// 2. == , !=
console.log(2 == 1);
console.log(2 != 1);

// 3. "2">1 & "02">1
console.log("2" > 1);
console.log("02" > 1);

// 4. (null > 0) , (null == 0) , (null >= 0)
console.log(null > 0);
console.log(null == 0);
console.log(null >= 0);

// 5. (==) & (> , < , >= , <=) works differently.

// 6. Undefined case.
console.log(undefined == 0);
console.log(undefined > 0);
console.log(undefined < 0);

// 7. strict check (===)
console.log("2" == 2);
console.log("2" === 2);